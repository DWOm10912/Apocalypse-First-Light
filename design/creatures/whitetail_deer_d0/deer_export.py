# (deer_lib.PX: the player's 0.9375 / 16 m). Java model px: (x, 24 - z, y). A clip rotation is deer_lib.Fig.pose's: per
# bone (x, y, z) degrees, Euler YXZ in armature axes about the bone's head, applied in the parent's posed frame:
# W_b = W_parent * T(P_b) * R_b * T(-P_b), the axes mapped (x, -z, y).
