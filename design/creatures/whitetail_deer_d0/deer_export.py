def mesh_json(f, scale):
    ob, me = f.ob, f.ob.data
    names = list(f.bones)
    index = {n: i for i, n in enumerate(names)}
    bones = [{"name": n, "parent": index[par] if par else -1, "pivot": java([c * scale for c in hd])}
             for n, (hd, tl, par) in f.bones.items()]
    uv = me.uv_layers.active.data
    verts, quads = [], []
    for poly in me.polygons:
        if len(poly.vertices) != 4:
            raise ValueError("not a quad: polygon %d" % poly.index)
        vs, ls = list(poly.vertices), list(poly.loop_indices)
        pj = [Vector(java([c / L.PX * scale for c in me.vertices[v].co])) for v in vs]
        nb = poly.normal
        nj = Vector((nb.x, -nb.z, nb.y))
        if (pj[2] - pj[0]).cross(pj[3] - pj[1]).dot(nj) < 0:
            vs, ls = vs[::-1], ls[::-1]
        quads.append(0)
        for v, l in zip(vs, ls):
            w = sorted(((ob.vertex_groups[g.group].name, g.weight) for g in me.vertices[v].groups if g.weight > 0),
                       key=lambda kv: -kv[1])[:4]
            tot = sum(x for _, x in w)
            js = [index[b] for b, _ in w] + [0] * (4 - len(w))
            ws = [round(x / tot, 5) for _, x in w] + [0.0] * (4 - len(w))
            u, vv = uv[l].uv
            verts += java([c / L.PX * scale for c in me.vertices[v].co]) + [round(u, 6), round(1 - vv, 6)] + js + ws
    return {
        "format_version": 1,
        "about": "AFL white-tailed deer (docs/gameplay/afl_whitetail_deer_d0_design.md 11), generated by "
                 "design/creatures/whitetail_deer_d0/deer_export.py from the D0 concept. Java model px; per quad 4 vertices "
                 "of x y z u v j0..j3 w0..w3; (p2-p0)x(p3-p1) points out of the part.",
        "scale": scale,
        "texture_size": L.ATLAS,
        "bones": bones,
        "parts": ["deer"],
        "quad_parts": quads,
        "vertices": verts,
    }


