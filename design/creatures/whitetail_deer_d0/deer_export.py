def add(*ds):
    out = {}
    for d in ds:
        for b, v in d.items():
            out[b] = tuple(a + c for a, c in zip(out.get(b, (0, 0, 0)), v))
    return out


def leg(front, side, phi, duty, A, F):
    """One leg at gait phase phi (0 = the hoof lands): the stance sweeps it from A deg forward to A back at an even pace;
    the swing brings it forward again with the knee (carpus) or the hock folded, most at mid-swing."""
    phi %= 1.0
    if phi < duty:
        a, f = A * (2 * phi / duty - 1), 0.0
    else:
        w = (phi - duty) / (1 - duty)
        s = w * w * (3 - 2 * w)
        a, f = A * (1 - 2 * s), math.sin(math.pi * w) * F
    if front:
        return {"fl_upper" + side: (a - 8 * f, 0, 0), "fl_cannon" + side: (72 * f, 0, 0), "fl_hoof" + side: (34 * f, 0, 0)}
    return {"hl_thigh" + side: (a - 10 * f, 0, 0), "hl_shin" + side: (26 * f, 0, 0), "hl_cannon" + side: (-58 * f, 0, 0),
            "hl_hoof" + side: (30 * f, 0, 0)}


def gait(p, offsets, duty, Af, Ah, F, extra=None):
    k = {}
    for (front, side), off in offsets.items():
        k.update(leg(front, side, p + off, duty, Af if front else Ah, F))
    return add(k, extra or {})


WALK = {(False, ".L"): 0.0, (True, ".L"): -0.25, (False, ".R"): -0.5, (True, ".R"): -0.75}   # lateral sequence
TROT = {(True, ".L"): 0.0, (False, ".R"): 0.0, (True, ".R"): -0.5, (False, ".L"): -0.5}       # diagonal pairs


def walk_key(p):
    c2 = math.cos(4 * math.pi * p)
    return gait(p, WALK, 0.62, 24, 22, 1.0, {"neck_1": (2 * c2, 0, 0), "head": (-1.5 * c2, 0, 0), "chest": (0, 1.5 * math.sin(2 * math.pi * p), 0)})


def trot_key(p):
    c2 = math.cos(4 * math.pi * p)
    return gait(p, TROT, 0.4, 32, 30, 1.25, {"neck_1": (8 + 3 * c2, 0, 0), "head": (-4, 0, 0)})


