def jquat(rot):
    q = Euler(tuple(math.radians(a) for a in rot), "YXZ").to_matrix().to_quaternion()
    return [round(q.x, 6), round(-q.z, 6), round(q.y, 6), round(q.w, 6)]


def hooves(f):
    ao = f.ao
    return {n: (ao.matrix_world @ ao.pose.bones[n].tail) / L.PX for n in ("fl_hoof.L", "fl_hoof.R", "hl_hoof.L", "hl_hoof.R")}


def cycle(f, keyf, offsets, duty):
    """Body travel per cycle: a hoof slides back S over its stance (duty of the cycle) while the body goes S forward, so
    one cycle is S / duty. S from the left forefoot, the pose's lift held (the hoof's own slide, not the body's bob).
    (The lowest-hoof sum under-counts once two hooves share the ground.)"""
    off = offsets[(True, ".L")]
    a, b = (-off) % 1.0, (-off + duty - 1e-4) % 1.0
    ys = []
    for p in (a, b):
        f.pose(keyf(p), ground=False)
        ys.append(hooves(f)["fl_hoof.L"].y)
    return (ys[1] - ys[0]) / duty


BOUND_CYCLE_PX = 5.2 / L.PX   # 2.5 strides a second at 13 m/s


def clips_json(f):
    names = list(f.bones)
    out = {}
    for name, c in clip_defs().items():
        keys = []
        for t, k, extra in c["keys"]:
            f.pose(k, lift=extra)
            keys.append({"t": round(t, 4), "lift": round(f.ao.location.z / L.PX, 4), "rot": [jquat(k.get(b, (0, 0, 0))) for b in names]})
        out[name] = {"length": c["keys"][-1][0], "loop": c["loop"], "ease": c["ease"], "keys": keys}
    f.pose({})
    return {
        "format_version": 1,
        "about": "AFL white-tailed deer clips, generated by design/creatures/whitetail_deer_d0/deer_export.py (the buck; the doe's "
                 "lift and cycles scale by its mesh scale). Per key: t (s; walk / trot / bound: the phase 0..1 of one cycle), lift "
                 "(model px the body is raised: the lowest point on the ground, plus the flight of a bound), rot per bone (x y z w, "
                 "Java model axes, the bone's turn in its parent's frame).",
        "bones": names,
        "walk_cycle_px": round(cycle(f, walk_key, WALK, 0.62), 3),
        "trot_cycle_px": round(cycle(f, trot_key, TROT, 0.4), 3),
        "bound_cycle_px": round(BOUND_CYCLE_PX, 3),
        "stomp_hit": 0.3,
        "clips": out,
    }


def blink(f, path):
    """The same atlas with the eyes shut (the lid in the head's colour)."""
    A = f.A
    lid = DB.HEADM * 0.82
    for fn, flip in (("left", False), ("right", True)):
        F = A.face("head", fn)
        W = F.shape[1]
        for r in (3, 4):
            for c in (3, 4):
                F[r, (W - 1 - c) if flip else c, :3] = lid
        F[4, (W - 1 - 4) if flip else 4, :3] = DB.EYE * 1.6     # the lash line
    A.image(path)


def dead(f, path):
    """The carcass's atlas: the eyes glazed (dull grey, no highlight) under a half-shut lid (user 2026-10-28: "死亡的眼睛和正常
    的是一样的")."""
    A = f.A
    lid = DB.HEADM * 0.82
    for fn, flip in (("left", False), ("right", True)):
        F = A.face("head", fn)
        W = F.shape[1]
        for c in (3, 4):
            cc = (W - 1 - c) if flip else c
            F[3, cc, :3] = lid                                   # the upper lid half down
            F[4, cc, :3] = DB.rgb("#55575A")                     # the glazed eye under it
    A.image(path)


def export():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(TEX, exist_ok=True)
    buck, doe, player = DB.build_all()
    for f in (buck, doe):
        s = DB.KINDS[f.kind]["scale"]
        f.ao.scale = (1, 1, 1)
        bpy.context.view_layer.update()
        json.dump(mesh_json(f, s), open(f"{OUT}/{f.kind}_mesh.json", "w"), separators=(",", ":"))
        shutil.copyfile(f"{DB.OUT}/deer_{f.kind}_atlas.png", f"{TEX}/{f.kind}.png")
        blink(f, f"{TEX}/{f.kind}_blink.png")
        dead(f, f"{TEX}/{f.kind}_dead.png")
    cj = clips_json(buck)
    json.dump(cj, open(f"{OUT}/clips.json", "w"), separators=(",", ":"))
    print("EXPORT", {"bones": len(cj["bones"]), "walk_cycle_px": cj["walk_cycle_px"], "trot_cycle_px": cj["trot_cycle_px"],
                     "quads": {f.kind: len(f.ob.data.polygons) for f in (buck, doe)}})


def check():
    """Every clip's keys side on (and the bound and death three-quarter too), one sheet per clip, for looking at."""
    out = HERE + "/r1/clips"
    os.makedirs(out, exist_ok=True)
    buck, doe, player = DB.build_all()
    figs = [buck, doe, player]
    for name, c in clip_defs().items():
        keys = c["keys"]
        if name in ("walk", "trot"):
            keys = keys[:-1:2]
        for i, (t, k, extra) in enumerate(keys):
            buck.pose(k, lift=extra)
            DB.shoot([buck], figs, (1, 0, 0.05), f"{out}/{name}_{i:02d}.png", res=(420, 360), target=(0, 0.05, 0.7), size=1.75, lens=50)
            if name in ("bound", "death", "look_back", "stomp"):
                DB.shoot([buck], figs, (0.85, -1, 0.25), f"{out}/{name}_{i:02d}_q.png", res=(420, 360), target=(0, 0, 0.7), size=1.9, lens=50)
    buck.pose({})
    print("CHECK done")


